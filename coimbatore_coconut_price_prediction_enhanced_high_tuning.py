def add_group_history(
    df,
    group_cols,
    value_col,
    prefix,
    lags,
    windows
):
    out = df.sort_values(
        group_cols + ["Date"]
    ).copy()

    grouped = out.groupby(
        group_cols,
        sort=False
    )[value_col]

    for lag in lags:
        out[f"{prefix}Lag_{lag}d"] = (
            grouped.shift(lag)
        )

    # transform(lambda ...) keeps the original row index and avoids
    # fragile MultiIndex rolling assignments.
    for window in windows:
        out[f"{prefix}RollMean_{window}d"] = (
            out.groupby(group_cols, sort=False)[value_col]
            .transform(
                lambda s: s.shift(1).rolling(
                    window,
                    min_periods=max(3, window // 4)
                ).mean()
            )
        )

        out[f"{prefix}RollStd_{window}d"] = (
            out.groupby(group_cols, sort=False)[value_col]
            .transform(
                lambda s: s.shift(1).rolling(
                    window,
                    min_periods=max(3, window // 4)
                ).std()
            )
        )

    return out

