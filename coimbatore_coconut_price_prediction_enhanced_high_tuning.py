def metrics(y_true, y_pred):
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    mask = np.abs(y_true) > 1e-12

    return {
        "MAE": mean_absolute_error(
            y_true,
            y_pred
        ),
        "RMSE": np.sqrt(
            mean_squared_error(
                y_true,
                y_pred
            )
        ),
        "R2": r2_score(
            y_true,
            y_pred
        ),
        "MAPE_%": (
            np.mean(
                np.abs(
                    (
                        y_true[mask]
                        - y_pred[mask]
                    )
                    / y_true[mask]
                )
            ) * 100
        )
    }

def make_ohe():
    # sklearn changed sparse= to sparse_output=.
    try:
        return OneHotEncoder(
            handle_unknown="ignore",
            sparse_output=True
        )
    except TypeError:
        return OneHotEncoder(
            handle_unknown="ignore",
            sparse=True
        )

def make_preprocessor(features):
    numeric = [
        c
        for c in features
        if c not in CATEGORICAL
    ]

    return ColumnTransformer(
        transformers=[
            (
                "cat",
                Pipeline([
                    (
                        "imputer",
                        SimpleImputer(
                            strategy="most_frequent"
                        )
                    ),
                    (
                        "onehot",
                        make_ohe()
                    )
                ]),
                CATEGORICAL
            ),
            (
                "num",
                SimpleImputer(
                    strategy="median"
                ),
                numeric
            )
        ]
    )

print("Utilities ready.")

