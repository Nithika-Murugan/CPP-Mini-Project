def ccf_scan(x, y, max_lag=365):
    records = []

    for lag in range(max_lag + 1):
        aligned = pd.concat(
            [x.shift(lag), y],
            axis=1
        ).dropna()

        if len(aligned) >= 30:
            corr = aligned.iloc[:, 0].corr(
                aligned.iloc[:, 1]
            )
        else:
            corr = np.nan

        records.append({
            "Lag": lag,
            "Correlation": corr,
            "AbsoluteCorrelation": (
                abs(corr)
                if pd.notna(corr)
                else np.nan
            ),
            "N": len(aligned)
        })

    return pd.DataFrame(records)

